{#
  原典のセルから前後の空白を落とす。

  ⚠️ **これは正規化であって、無害ではない。**
  TS 版はここを黙ってやっており、原典に全角スペース（U+3000）が入っていることに
  誰も気づいていなかった（`01郵便料　`）。実測で全 45,038 セル中3セル。

  trim する理由は識別子の安定性にある。識別子はセル全文から導出しており
  公開 API の一部なので、既に配布した permalink を変えられない。

  DuckDB の `\s` は ASCII のみなので、全角スペースを明示的に列挙する。
  JavaScript の String.trim() は Unicode 空白全般を落とすため、そちらに合わせている。
#}
{% macro trim_cell(col) -%}
    trim({{ col }}, ' \t\n\r　')
{%- endmacro %}
