{#
  原典のセルから前後の空白を落とす。

  ⚠️ **これは正規化であって、無害ではない。**
  TS 版はここを黙ってやっており、原典に全角スペース（U+3000）が入っていることに
  誰も気づいていなかった（`01郵便料　`）。実測で全 45,038 セル中3セル。

  trim する理由は識別子の安定性にある。識別子はセル全文から導出しており
  公開 API の一部なので、既に配布した permalink を変えられない。

  ⚠️ **落とすのは「Unicode 空白全般」ではない。** 半角スペース・タブ・改行・CR・全角スペースの5文字だけ。
  DuckDB の `\s` は ASCII のみなので明示的に列挙している。

  ⚠️ **trim は可逆でない。** コードと名称の分離は繋げば原文へ戻るが、
  落とした空白は正本から復元できない。原典を `data/budget/raw/` に保全し、
  変更した箇所を警告として毎回報告することで担保している。
#}
{% macro trim_cell(col) -%}
    trim({{ col }}, ' \t\n\r　')
{%- endmacro %}
